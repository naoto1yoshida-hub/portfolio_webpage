def get_case(slug):
    """slug からケーススタディを1件返す。該当なしは None。"""
    for case in CASES:
        if case["slug"] == slug:
            return case
    return None


def featured_cases(limit=4):
    """トップページに大きく出すケースを featured 順に返す。"""
    ordered = sorted(CASES, key=lambda c: c.get("featured", 99))
    return ordered[:limit]


def all_cases():
    """ケーススタディを featured 順に返す。"""
    return sorted(CASES, key=lambda c: c.get("featured", 99))


def total_count():
    """掲載している実績の総件数。"""
    return len(CASES) + len(OTHER_WORKS)


def works_by_category():
    """カテゴリごとに [(カテゴリ定義, 実績リスト), ...] を返す。

    ケーススタディは詳細ページへのリンクを持つため `detail_slug` を添えて混ぜる。
    """
    grouped = []
    for category in CATEGORIES:
        items = []
        for case in all_cases():
            if case["category"] != category["key"]:
                continue
            items.append({
                "title": case["title"],
                "status": case.get("badge", case["status"]),
                "client": case["client"],
                "summary": case["summary"],
                "stack": " / ".join(part["items"] for part in case["stack"]),
                "detail_slug": case["slug"],
            })
        for work in OTHER_WORKS:
            if work["category"] != category["key"]:
                continue
            items.append({
                "title": work["title"],
                "status": work["status"],
                "client": work["client"],
                "summary": work["summary"],
                "stack": work["stack"],
                "url": work.get("url"),
                "detail_slug": None,
            })
        if items:
            grouped.append((category, items))
    return grouped
